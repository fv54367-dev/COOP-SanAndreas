#pragma once
#include "network/packets/train.h"

class CVehicle;
class CNetworkVehicle;

// Track-mirror train sync (TANDA_2026-11-10_glm_sync_trenes, design ported from project_gta_sa_coop
// docs/design/trains.md GPL-3.0). The host simulates every train (T-D4); every other game holds a real copy built
// with the game's own CTrain::CreateMissionTrain (same configuration, track, node) and drives the copy's engine by
// rail distance (TRAIN_STATE 5 Hz), so the game code itself places every carriage. Carriages are ordinary network
// vehicle records used for identity only (seats, blips, shots, peds inside). Random trains are generated by the
// host only (T-D2) and a random train a network player rides is kept (T-D3). A derailed train removes its copies
// until the physics tanda. Switch: train-sync (CConfigLoader::ms_bTrainSync).
class CTrainSync
{
public:
    static bool IsEnabled();

    static void Process();        // 200 ms tick from Main.cpp: host scan/state, follower watchdogs
    static void SendSnapshot();   // host: everything to everyone (PLAYER_CONNECTED)

    static void OnBecameHost();
    static void OnBecameFollower();

    static void HandleSpawn(Packets::Trains::TrainEvent* packet);    // SPAWN and SNAPSHOT kinds
    static void HandleRemove(Packets::Trains::TrainEvent* packet);
    static void HandleState(Packets::Trains::TrainState* packet);

    // the copy's engine follows the host's rail distance, never this game's physics; called FIRST from
    // CVehicle__ProcessControl_Hook (before the local-player branch), returns true when it handled the vehicle
    static bool OverrideCopyProcessControl(CVehicle* vehicle);

    // the game's random-train generator call (0x43426D) passes through here: a follower skips it entirely, the
    // host runs it keeping trains near network players (the generator only knows the host's own camera)
    static void ProcessGeneration();

    // vehicle-sync carve-outs
    static bool IsSyncedCarriage(const CNetworkVehicle* vehicle);   // train record: its motion belongs to TRAIN_STATE
    static bool OnCarriageRecordRemoved(CNetworkVehicle* record);   // one removed copy carriage removes the whole chain
    static void EvictCosmeticDriver(CVehicle* vehicle);             // the copy's local NPC driver goes before a real occupant warps in
};
