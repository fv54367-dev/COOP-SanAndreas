#pragma once

// Stream in/out of remote ambient vehicles and peds: far away ones only keep their CNetworkVehicle/CNetworkPed record
// (last position, health, damage...) and get created again when the local player comes close. This keeps the game's
// vehicle/ped pools and the model streaming free of entities nobody near us can see.
// Never streamed out: entities synced by this client, mission entities and vehicles with a player inside.
class CStreamingSync
{
public:
    static constexpr float VEHICLE_STREAM_IN = 220.0f;
    static constexpr float VEHICLE_STREAM_OUT = 260.0f;
    static constexpr float AIRCRAFT_STREAM_IN = 450.0f;
    static constexpr float AIRCRAFT_STREAM_OUT = 500.0f;
    static constexpr float PED_STREAM_IN = 120.0f;
    static constexpr float PED_STREAM_OUT = 150.0f;

    // players closer than this share the ambient traffic/pedestrians: only the one with the lowest id generates them
    static constexpr float SHARED_GENERATION_RADIUS = 300.0f;

    // zone-population: a spawn point belongs to the closest player in 2D; within this margin of a tie the player
    // with the lowest id wins (the remote position can lag a bit)
    static constexpr float POINT_OWN_TIE_MARGIN = 5.0f;

    // interior duplicates: a remote ped whose area is unknown is taken as inside our interior when it is this close
    // (interior coordinates are far away from the main map)
    static constexpr float INTERIOR_SAME_AREA_RADIUS = 60.0f;

    static void Process();

    // true if another player with a lower id is within SHARED_GENERATION_RADIUS, this client must not generate
    // new ambient vehicles/peds (he already fills the area and every client receives them)
    static bool IsOtherPlayerGeneratingNearby();

    // zone-population: true if the ambient entity the game wants to create at `p` is ours. Among the network
    // players of our area (m_nAreaCode) we own it when we are the closest to `p` in 2D, the lowest id winning
    // within POINT_OWN_TIE_MARGIN. Inside an interior (area != 0) it is always ours: CInteriorOwnership decides
    static bool IsPointMine(const CVector& p);

    // ambient entities: the traffic / pedestrians generated by the game (mission entities stay with their client)
    static bool IsAmbientVehicle(unsigned char createdBy);
    static bool IsAmbientPed(unsigned char createdBy);

    // should a remote ambient entity spawned at this position be created right away?
    static bool ShouldCreateVehicleAt(int modelId, unsigned char createdBy, const CVector& pos);
    static bool ShouldCreatePedAt(unsigned char createdBy, const CVector& pos);

    // should a PED_SPAWN arriving from another player be created only as a suppressed record? (we own the interior the
    // sender is in: only its owner hosts the population)
    static bool ShouldSuppressPedSpawn(unsigned char createdBy, const CVector& pos, unsigned char creatorArea);

    // area of the interior the local player is in (0 = main map)
    static unsigned char GetLocalInteriorArea();
};
